import fs from "node:fs";
import path from "node:path";
import termsJson from "../config/terms.json";

export const OUT_DIR = path.resolve(__dirname, "../../packages/chain-client/src/generated");

const CONTRACTS: [name: string, artifact: string, exportName: string][] = [
  ["CringeCourt", "src/CringeCourt.sol/CringeCourt.json", "cringeCourtAbi"],
  ["HumanRegistry", "src/HumanRegistry.sol/HumanRegistry.json", "humanRegistryAbi"],
  ["MockUSDC", "src/test/MockUSDC.sol/MockUSDC.json", "mockUsdcAbi"],
];

const HEADER = "// GENERATED by contracts/scripts/export-abis.ts — do not edit by hand.\n";

/** Returns file name -> file content for packages/chain-client/src/generated. */
export function renderBindings(): Record<string, string> {
  const files: Record<string, string> = {};
  let abis = HEADER;
  for (const [, artifact, exportName] of CONTRACTS) {
    const json = JSON.parse(fs.readFileSync(path.resolve(__dirname, "../artifacts", artifact), "utf8"));
    abis += `\nexport const ${exportName} = ${JSON.stringify(json.abi, null, 2)} as const;\n`;
  }
  const mock = JSON.parse(fs.readFileSync(path.resolve(__dirname, "../artifacts", CONTRACTS[2][1]), "utf8"));
  abis += `\n/** MockUSDC creation bytecode, for local deployments in tests only. */\nexport const mockUsdcBytecode = ${JSON.stringify(mock.bytecode)} as const;\n`;
  files["abis.ts"] = abis;
  files["terms.ts"] = `${HEADER}// Source: contracts/config/terms.json (docs/DECISIONS.md implementation constants).\n\nexport const termsConfig = ${JSON.stringify(termsJson, null, 2)} as const;\n`;
  return files;
}
