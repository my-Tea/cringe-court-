/* ── Complete examples inside the mode docs (docs/ai/02-04) ──────────────── */

export const EXAMPLES_BEGIN = '<!-- BEGIN GENERATED EXAMPLES (npm run court:prompts) -->';
export const EXAMPLES_END = '<!-- END GENERATED EXAMPLES -->';
export const MODE_DOC_FILES: Readonly<Record<CourtMode, string>> = { solo: '02_SOLO_CASE_LOGIC.md', versus: '03_VERSUS_CASE_LOGIC.md', viral: '04_VIRAL_CASE_LOGIC.md' };

const DISPLAY: Readonly<Record<string, string>> = { prosecutor: PERSONAS.prosecutor.name, defense: PERSONAS.defense.name, judge: PERSONAS.judge.name, clerk: 'Court Clerk' };

function renderExample(n: number, input: CaseInput, raw: string): string {
  const c = prepareCase(input);
  const plan = PLANS[c.mode];
  const parsed = JSON.parse(raw) as { lines: { slot: string; speaker: string; emotion?: string; animation?: string; text: string }[] };
  const bySlot = new Map(parsed.lines.map((l) => [l.slot, l]));
  const performed = plan.slots.map((s) => {
    if (s.template) {
      const speaker = s.role === 'judge' || s.role === 'clerk' ? s.role : 'judge';
      return `| ${s.id} | ${DISPLAY[speaker]} *(court-written)* | ${s.template(c)} |`;
    }
    const l = bySlot.get(s.id);
    const side = s.role === 'benchA' ? ` for ${c.ballot[0]}` : s.role === 'benchB' ? ` for ${c.ballot[1]}` : '';
    return `| ${s.id} | ${DISPLAY[l?.speaker ?? ''] ?? l?.speaker}${side} · ${l?.emotion ?? 'neutral'}, ${l?.animation ?? 'talk'} | ${l?.text ?? ''} |`;
  });
  const chars = c.facts.map((f) => `- ${f.id} *(${f.status}${f.sourceId ? `, ${f.sourceId}` : ''})*: ${f.text}`);
  const adv = c.advocates ? `Advocates (court coin flip on the case id): ${DISPLAY[c.advocates.A]} argues ${c.ballot[0]} (${c.parties.sideA}), ${DISPLAY[c.advocates.B]} argues ${c.ballot[1]} (${c.parties.sideB}).` : 'Miss Ratio prosecutes, Counsel Chaos defends.';
  return `### Example ${n}: ${c.title}

Input (\`CaseInput\`):

${fence('json', JSON.stringify(input, null, 2))}

Preparation (deterministic, no AI): category \`${c.category}\`, tone \`${c.tone}\`, ballot ${c.ballot.join(' / ')}. ${adv}

${chars.join('\n')}

<details><summary>Model output (the JSON the model returns for this case)</summary>

${fence('json', JSON.stringify(JSON.parse(raw), null, 1))}

</details>

As performed (model lines plus the court-written lines):

| Slot | Speaker | Line |
|---|---|---|
${performed.map((r) => r.replace(/\n/g, ' ')).join('\n')}

Checker result:

${findings(c.mode, raw, input)}
`;
}

/** The generated example section for each mode doc: the reference case plus two more. */
export function modeExampleSections(): { mode: CourtMode; file: string; content: string }[] {
  return (['solo', 'versus', 'viral'] as const).map((mode) => {
    const extra = DOC_EXAMPLES.filter((e) => e.input.mode === mode);
    const blocks = [renderExample(1, EXAMPLE_INPUTS[mode], exampleScript(mode)), ...extra.map((e, i) => renderExample(i + 2, e.input, JSON.stringify(e.script)))];
    return { mode, file: MODE_DOC_FILES[mode], content: `${EXAMPLES_BEGIN}\n\n${blocks.join('\n')}\n${EXAMPLES_END}` };
  });
}

/** Replace the generated region of a mode doc; returns null if the markers are missing. */
export function withExampleSection(doc: string, section: string): string | null {
  const a = doc.indexOf(EXAMPLES_BEGIN);
  const b = doc.indexOf(EXAMPLES_END);
  if (a < 0 || b < a) return null;
  return doc.slice(0, a) + section + doc.slice(b + EXAMPLES_END.length);
}

export function promptDocs(): { file: string; content: string }[] {
  return [
    { file: 'shared-system.md', content: sharedDoc() },
    { file: 'solo-trial.md', content: trialDoc('solo') },
    { file: 'versus-trial.md', content: trialDoc('versus') },
    { file: 'viral-trial.md', content: trialDoc('viral') },
    { file: 'post-verdict.md', content: postVerdictDoc() },
  ];
}
