import { EXAMPLE_INPUTS, exampleScript } from './examples';

const GENERATED = '<!-- GENERATED by `npm run court:prompts` from packages/ai/src/court/prompts.ts, plans.ts and personas.ts. Do not edit by hand. -->';

const fence = (lang: string, body: string) => `\`\`\`${lang}\n${body}\n\`\`\``;

/** A deliberately weak script: generic, ungrounded, verdict-leaking. Shows what the checker catches. */
function weakScript(mode: CourtMode): string {
  const c = prepareCase(EXAMPLE_INPUTS[mode]);
  const generic: Record<string, string> = {
    prosecutor: 'Your Honor, this decision was bad and everyone knows it. Objection! Bro is cooked, bro is cooked.',
    defense: 'Objection! My client did nothing wrong. This decision was good actually and that is all.',
    judge: 'Order! Honestly the court thinks this one is guilty but let us continue anyway.',
    clerk: 'Case.',
  };
  const lines = PLANS[mode].slots
    .filter((s) => !s.template)
    .map((s) => {
      const speaker = s.role === 'benchA' ? (c.advocates?.A ?? 'prosecutor') : s.role === 'benchB' ? (c.advocates?.B ?? 'defense') : s.role;
      return { slot: s.id, speaker, emotion: 'angry', animation: 'objection', camera: 'auto', crowd: 'gasp', text: generic[speaker] ?? 'Objection!', factRefs: [] };
    });
  return JSON.stringify({ analysis: { core: 'This decision was bad.', tension: 'It was bad.', benchA: 'It was bad.', benchB: 'It was fine.', factRefs: [] }, lines });
}

function findings(mode: CourtMode, raw: string, input: CaseInput = EXAMPLE_INPUTS[mode]): string {
  const c = prepareCase(input);
  const p = parseModelScript(raw, new Set(c.facts.map((f) => f.id)));
  if (p.kind === 'error') return `- parse error (${p.code}): ${p.message}`;
  if (p.kind === 'refusal') return `- refusal: ${p.refusal}`;
  const r = checkScript(c, PLANS[mode], p.script);
  const unique = new Map<string, string>();
  for (const i of r.issues) if (!unique.has(i.code)) unique.set(i.code, `- **${i.severity}** \`${i.code}\`: ${i.message}`);
  const coerced = p.coercions.map((x) => `- coerced: ${x}`);
  const found = [...unique.values(), ...coerced];
  return [`Heuristic estimate: ${r.overall} / 5 (${Object.entries(r.scores).map(([k, v]) => `${k} ${v}`).join(', ')})`, '', ...(found.length ? found : ['- no issues'])].join('\n');
}

const TITLES: Readonly<Record<CourtMode, string>> = { solo: 'Solo Court trial prompt', versus: 'Versus Court trial prompt', viral: 'Viral Court trial prompt' };

function trialDoc(mode: CourtMode): string {
  const c = prepareCase(EXAMPLE_INPUTS[mode]);
  const [, user] = trialMessages(c);
  const plan = PLANS[mode];
  return `${GENERATED}

# ${TITLES[mode]} (\`${plan.version}\`)

Sent as the **user** message after the shared system prompt (\`shared-system.md\`). One request per trial; one optional repair turn (see \`shared-system.md\` §Repair).

## Variables

| Placeholder in the rendered prompt | Source |
|---|---|
| Mode rules, category angle | \`MODE_RULES\` / \`CATEGORY_ANGLES\` in \`prompts.ts\`, chosen by \`PreparedCase.mode\` and \`.category\` |
| Advocate names per side | \`PreparedCase.advocates\` (court-assigned coin flip on the case id; never the model) |
| Trial plan | \`PLANS.${mode}\` in \`plans.ts\` (slot ids, speakers, character ranges, \`answers\` links) |
| Length target | \`lengthTarget()\`: ${plan.targetSeconds[0]}-${plan.targetSeconds[1]} s at 15 characters/second |
| \`<case_data>\` | \`caseData(PreparedCase)\`: redacted, numbered facts; \`<\` and \`>\` escaped |

## Rendered for the reference case

Input: \`${JSON.stringify(EXAMPLE_INPUTS[mode])}\`

${fence('text', user?.content ?? '')}

## Strong output (reference)

${fence('json', exampleScript(mode))}

Checker result:

${findings(mode, exampleScript(mode))}

## Weak output (what the checker rejects)

${fence('json', weakScript(mode))}

Checker result:

${findings(mode, weakScript(mode))}
`;
}

function sharedDoc(): string {
  const repair = 'The court\'s script checker found problems with that JSON:\n- [L04] <finding>\n- ...\n\nRewrite the complete JSON object fixing every problem. Keep the lines that worked. Same slots, same rules, JSON only.';
  return `${GENERATED}

# Shared system prompt (\`${PROMPT_VERSIONS.shared}\`)

Sent as the **system** message for every trial in every mode. The mode prompt (\`solo-trial.md\`, \`versus-trial.md\`, \`viral-trial.md\`) follows as the user message.

${fence('text', sharedSystemPrompt())}

## Repair

When the first answer fails validation, the harness sends the original two messages, the model's answer as an \`assistant\` message, then this user message (at most 12 findings, hard ones first). There is at most one repair turn by default (\`maxAttempts: 2\`).

${fence('text', repair)}

## Refusal

The model may answer \`{"refusal":"unsuitable","reason":"..."}\` or \`{"refusal":"insufficient-facts"}\`. The harness turns that into \`TrialGenerationError('refused')\` without retrying.
`;
}

