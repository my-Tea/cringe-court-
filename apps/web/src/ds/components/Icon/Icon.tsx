export type IconName = keyof typeof GLYPHS;
export const ICON_NAMES = Object.keys(GLYPHS) as IconName[];

/** Merge each row's runs of '#' into rects, emitted as one path. */
function toPath(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      const start = x;
      while (row[x] === '#') x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(GLYPHS).map(([k, rows]) => [k, toPath(rows)])) as Record<IconName, string>;

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName;
  /** Accessible name. Omit for decorative icons (the default). */
  title?: string;
  size?: number | string;
}

export function Icon({ name, title, size = '1em', ...rest }: IconProps) {
  const a11y = title ? { role: 'img' as const, 'aria-label': title } : { 'aria-hidden': true as const };
  return (
    <svg
      viewBox="0 0 12 12"
      width={size}
      height={size}
      fill="currentColor"
      shapeRendering="crispEdges"
      focusable="false"
      data-icon={name}
      {...a11y}
      {...rest}
    >
      <path d={PATHS[name]} />
    </svg>
  );
}
