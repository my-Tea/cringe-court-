export type SoloIconName = keyof typeof GLYPHS;

function toPath(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      const start = x;
      while (row[x] === '#') x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(GLYPHS).map(([k, rows]) => [k, toPath(rows)])) as Record<SoloIconName, string>;

export function SoloIcon({ name, ...rest }: { name: SoloIconName } & Omit<SVGProps<SVGSVGElement>, 'children'>) {
  return (
    <svg viewBox="0 0 12 12" width="1em" height="1em" fill="currentColor" shapeRendering="crispEdges" aria-hidden focusable="false" {...rest}>
      <path d={PATHS[name]} />
    </svg>
  );
}
